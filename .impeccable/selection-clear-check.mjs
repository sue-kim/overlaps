import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH});
try {
 const page=await browser.newPage({viewport:{width:1366,height:900}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.addInitScript(()=>Object.defineProperty(navigator,'clipboard',{value:{writeText:async text=>{window.copiedAvailability=text;}}}));
 await page.goto('http://127.0.0.1:5173');
 await page.clock.install();
 const time=page.getByLabel('Time',{exact:true});
 const date=page.getByLabel('Date',{exact:true});
 const save=page.getByRole('button',{name:'Save availability',exact:true});
 const quickSave=page.getByRole('button',{name:'Save selected calendar time',exact:true});
 await page.locator('.time-cell[data-slot$="09:00"]').first().click();
 const selectedDate=await date.inputValue();
 await page.getByRole('heading',{name:'Find a time',exact:true}).click();
 assert.equal(await time.inputValue(),'09:00');
 await quickSave.click();
 await page.locator('.time-cell[data-slot$="10:00"]').first().click();
 await quickSave.click();
 await page.locator('.local-date').click();
 assert.equal(await time.inputValue(),'');
 assert.equal(await date.inputValue(),'');
 assert.equal(await page.locator('.selection-event,.day-heading.is-chosen,.comparison-row').count(),0);
 assert.equal(await save.isDisabled(),true);
 await page.clock.fastForward(16000);
 assert.equal(await time.inputValue(),'','Clock updates must not repopulate the cleared fields');
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('overlap-slots')));
 assert.equal(saved.length,2);
 await page.getByRole('button',{name:'Copy times (2 saved)',exact:true}).click();
 const copied=await page.evaluate(()=>window.copiedAvailability);
 assert.equal((copied.match(/Seoul time:/g)||[]).length,1);
 assert.match(copied,/9:00–11:00 AM/);
 await date.fill(selectedDate);await time.fill('11:15');
 assert.equal(await page.locator('.comparison-row').count(),3);
 assert.equal(await save.isDisabled(),false);
 await page.locator('.local-date').click();
 await page.locator('.time-cell[data-slot$="12:00"]').first().click();
 assert.equal(await time.inputValue(),'12:00');
 assert.equal(await page.locator('.selection-event').count(),1);
 await page.locator('.local-date').click();
 await page.getByRole('button',{name:'Next week',exact:true}).click();
 assert.equal(await page.locator('.selection-event').count(),0);
 await page.setViewportSize({width:390,height:844});
 await page.locator('.time-cell[data-slot$="09:00"]').first().click();
 await page.locator('footer').click();
 assert.equal(await time.inputValue(),'');
 assert.deepEqual(errors,[]);
 console.log('Passed: click-away clears fields/highlights, panel stays editable, live ticks stay cleared, saved times remain copyable, calendar re-selection and mobile dismissal work.');
}finally{await browser.close();}
