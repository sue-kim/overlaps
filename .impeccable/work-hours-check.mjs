import { chromium } from 'playwright';
import { DateTime } from 'luxon';
import assert from 'node:assert/strict';
import { workHoursInDay } from '../src/workHours.ts';
const day=DateTime.fromISO('2026-09-29',{zone:'Asia/Seoul'});
const sf=workHoursInDay(day,'America/Los_Angeles');
assert.deepEqual(sf.map(p=>[p.start.setZone('Asia/Seoul').toFormat('HH:mm'),p.end.setZone('Asia/Seoul').toFormat('HH:mm')]),[['01:00','10:00']]);
assert.equal(workHoursInDay(DateTime.fromISO('2026-10-03',{zone:'Asia/Seoul'}),'America/New_York').length,1,'Friday US work should extend into Korean Saturday');
assert.equal(workHoursInDay(DateTime.fromISO('2026-10-04',{zone:'Asia/Seoul'}),'America/New_York').length,0);
assert.equal(workHoursInDay(DateTime.fromISO('2026-12-01',{zone:'Asia/Seoul'}),'America/Los_Angeles')[0].start.setZone('Asia/Seoul').hour,2,'winter offset moves SF work by one hour');
