import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH});
try {
 const page=await browser.newPage({viewport:{width:1366,height:900}});
 await page.goto('http://127.0.0.1:5173');
 const cell=page.locator('.time-cell[data-slot$="09:00"]').first();
 await cell.click();
 const save=page.getByRole('button',{name:'Save selected calendar time',exact:true});
 await save.click();
 const saved=page.getByRole('button',{name:'Selected calendar time saved',exact:true});
 assert.equal(await saved.isDisabled(),true);
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('overlap-slots')).length),1);
 await page.getByLabel('Duration',{exact:true}).selectOption('15');
 await save.click();
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('overlap-slots')).length),2);
 await page.getByLabel('Duration',{exact:true}).selectOption('60');
 await page.locator('.time-cell[data-slot$="23:30"]').last().click();
 const box=await save.boundingBox();const grid=await page.locator('.calendar-scroll').boundingBox();
 assert.ok(box.y>=grid.y&&box.y+box.height<=grid.y+grid.height,'Save button stays inside the calendar at midnight');
 await save.click();
 await page.reload();
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('overlap-slots')).length),3);
 await page.locator('.time-cell[data-slot$="10:00"]').first().click();
 await page.mouse.move(0,0);
 await page.screenshot({path:'.impeccable/review/calendar-save-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.locator('.time-cell[data-slot$="10:30"]').first().click();
 await page.locator('.calendar-panel').screenshot({path:'.impeccable/review/calendar-save-mobile.png'});
 await save.click();
 assert.equal(await saved.isDisabled(),true);
 console.log('Calendar save verified: direct selection/save, saved state, 15-minute and midnight slots, persistence, and mobile save.');
}finally{await browser.close();}
